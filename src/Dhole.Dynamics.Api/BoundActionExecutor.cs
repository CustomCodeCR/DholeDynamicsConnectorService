using System.Net.Http.Headers;
using System.Security.Claims;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Dhole.Dynamics.Contracts;
using Dhole.Dynamics.Infrastructure;

namespace Dhole.Dynamics.Api;

/// <summary>Single dispatch of a preapproved bound Dataverse action, with durable no-retry semantics.</summary>
public sealed class BoundActionExecutor(ActionPolicyRepository policies,ClientAccessRepository clients,
    WriteLedger ledger,HttpClient http,IDataverseAccessTokenProvider tokens,
    ProductionWritePolicy? production = null)
{
    public async Task<WriteResult> InvokeAsync(ClaimsPrincipal actor,WritePolicy connection,
        string actionName,Guid recordId,IReadOnlyDictionary<string,JsonElement> data,
        string idempotencyKey,int revision,CancellationToken ct)
    {
        // Bound actions may be destructive; require BOTH approvals in Production.
        production?.Demand("action");
        if(recordId==Guid.Empty || !WriteLedger.ValidKey(idempotencyKey) ||
            !System.Text.RegularExpressions.Regex.IsMatch(actionName??"",
                @"^[A-Za-z][A-Za-z0-9_]{0,79}$"))
            throw new ReadRejected(400,"invalid_bound_action");
        var policy=await policies.FindAsync(connection.Connection.Id,connection.Table.LogicalName,actionName,ct);
        if(policy is not {Enabled:true} ||
            policy.Parameters.Count!=data.Count ||
            policy.Parameters.Any(p=>!data.TryGetValue(p.Name,out var value) ||
                !TemplateMapper.Typed(p.Type,value)))
            throw new ReadRejected(403,"action_policy_denied");
        if(!ScopeSecurity.HasScope(actor,"dynamics.actions.invoke"))
            throw new ReadRejected(403,"action_scope_denied");
        var issuer=actor.FindFirst("connector:issuer")?.Value;
        var client=ScopeSecurity.ClientId(actor);
        if(string.IsNullOrEmpty(issuer)||string.IsNullOrEmpty(client))
            throw new ReadRejected(403,"client_denied");
        var required=new[]{"__action_"+actionName}.Concat(data.Keys).ToArray();
        var grant=await clients.AuthorizeAsync(issuer,client,connection.Connection.Code,
            connection.Table.LogicalName,"action",required,ct);
        if(grant==GrantDecision.QuotaExceeded)throw new ReadRejected(429,"action_quota_exceeded");
        if(grant!=GrantDecision.Allowed)throw new ReadRejected(403,"action_grant_denied");

        var intent=JsonSerializer.Serialize(new {
            connection=connection.Connection.Id, revision, snapshot=connection.Snapshot.Version,
            entity=connection.Table.LogicalName,actionName,recordId,
            fields=data.OrderBy(x=>x.Key,StringComparer.Ordinal).ToArray()
        });
        var hash=Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(intent)));
        var reservation=await ledger.ReserveAsync(connection.Connection.Id,issuer,client,idempotencyKey,
            hash,connection.Table.LogicalName,"action",null,ct);
        if(!reservation.Created)
        {
            if(reservation.Status is "succeeded" or "rejected" && reservation.Previous is { } previous)
                return previous with {Replay=true};
            throw new ReadRejected(409,"action_pending_reconciliation");
        }

        try
        {
            if(!DataverseUrlValidator.TryNormalize(connection.Connection.DataverseUrl,out var host))
                throw new ReadRejected(400,"invalid_dataverse_host");
            var path="/api/data/v9.2/"+connection.Table.EntitySetName+"("+
                recordId.ToString("D")+")/Microsoft.Dynamics.CRM."+actionName;
            var uri=new Uri(new Uri(host),path);
            // The URL is *entirely* generated by the server from the pinned host, metadata and
            // a separately approved action name. No user supplied URL or HTTP method.
            using var request=new HttpRequestMessage(HttpMethod.Post,uri);
            request.Headers.Authorization=new AuthenticationHeaderValue("Bearer",
                await tokens.AcquireAsync(connection.Connection,ct));
            request.Headers.TryAddWithoutValidation("OData-Version","4.0");
            request.Content=new StringContent(JsonSerializer.Serialize(data),Encoding.UTF8,"application/json");
            using var response=await http.SendAsync(request,HttpCompletionOption.ResponseHeadersRead,ct);
            var status=(int)response.StatusCode;
            var result=status>=500?"ambiguous":status is >=200 and <300?"succeeded":"rejected";
            var retry=response.Headers.RetryAfter?.Delta is TimeSpan delay
                ? (int?)Math.Max(1,(int)Math.Ceiling(delay.TotalSeconds)) : null;
            return await ledger.CompleteAsync(reservation.Id,connection.Connection.Id,client,
                result,status,recordId,null,actionName,CancellationToken.None,retry);
        }
        catch(Exception ex) when(ex is HttpRequestException or TaskCanceledException or IOException
            or Microsoft.Identity.Client.MsalException)
        {
            return await ledger.CompleteAsync(reservation.Id,connection.Connection.Id,client,
                "ambiguous",null,recordId,null,"manual-reconciliation-required",
                CancellationToken.None);
        }
    }
}
